"""Streamlit dashboard. Run with:  streamlit run app.py"""
import streamlit as st
from modules.inventory import Inventory
from modules.price_analyzer import PriceAnalyzer
from modules.depreciation import (depreciation_by_age, depreciation_by_category,
                                  fit_depreciation_rate, predict_value)
from analytics import visualization as viz
from analytics.statistics import summary_stats
from utils.validation import ValidationError, CONDITIONS, CURRENT_YEAR

st.set_page_config(page_title="Second-Hand Price Intelligence", layout="wide")
st.title("Second-Hand Product Price Intelligence System")
st.caption("Data in data/products.csv. If it was generated by generate_data.py, it is SYNTHETIC.")

if "inv" not in st.session_state:
    try:
        st.session_state.inv = Inventory("data/products.csv")
    except (FileNotFoundError, ValueError) as e:
        st.error(str(e))
        st.stop()

inv = st.session_state.inv
df = inv.df
analyzer = PriceAnalyzer(df)

page = st.sidebar.radio("Navigate", ["Dashboard", "Price Check", "Browse Listings",
                                     "Manage Listings", "Brand Analysis", "Depreciation"])

# ---------------------------------------------------------------- Dashboard
if page == "Dashboard":
    analyzed = analyzer.analyze_all() if len(df) <= 3000 else None
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Listings", len(df))
    c2.metric("Average price", f"Rs {df['listed_price'].mean():,.0f}")
    c3.metric("Median price", f"Rs {df['listed_price'].median():,.0f}")
    if analyzed is not None:
        over = (analyzed["verdict"] == "Potentially overpriced").mean() * 100
        c4.metric("Potentially overpriced", f"{over:.1f}%")
    col1, col2 = st.columns(2)
    category = col1.selectbox("Category", ["All"] + sorted(df["category"].unique()))
    sub = df if category == "All" else df[df["category"] == category]
    col1.pyplot(viz.price_distribution(sub))
    col2.pyplot(viz.price_vs_age(sub))
    if analyzed is not None:
        st.pyplot(viz.verdict_counts(analyzed))
        st.subheader("Top 10 potentially overpriced listings")
        st.dataframe(analyzed.sort_values("diff_pct", ascending=False).head(10)
                     [["product_id", "brand", "model", "condition", "listed_price",
                       "fair_price", "diff_pct"]])
        st.subheader("Top 10 potentially undervalued listings")
        st.dataframe(analyzed.sort_values("diff_pct").head(10)
                     [["product_id", "brand", "model", "condition", "listed_price",
                       "fair_price", "diff_pct"]])

# -------------------------------------------------------------- Price Check
elif page == "Price Check":
    st.subheader("Is this listing fairly priced?")
    c1, c2, c3 = st.columns(3)
    category = c1.selectbox("Category", sorted(df["category"].unique()))
    d1 = df[df["category"] == category]
    brand = c2.selectbox("Brand", sorted(d1["brand"].unique()))
    d2 = d1[d1["brand"] == brand]
    model = c3.selectbox("Model", sorted(d2["model"].unique()))
    d3 = d2[d2["model"] == model]
    c4, c5, c6, c7 = st.columns(4)
    ram = c4.selectbox("RAM (GB)", sorted(d3["ram_gb"].unique()))
    storage = c5.selectbox("Storage (GB)", sorted(d3["storage_gb"].unique()))
    condition = c6.selectbox("Condition", CONDITIONS, index=1)
    release_year = c7.number_input("Release year", 2000, CURRENT_YEAR,
                                   int(d3["release_year"].mode()[0]))
    asking = st.number_input("Seller's asking price (Rs)", min_value=1000, value=20000, step=500)

    if st.button("Analyze price"):
        item = dict(category=category, brand=brand, model=model, ram_gb=ram,
                    storage_gb=storage, condition=condition,
                    release_year=int(release_year), listed_price=float(asking))
        try:
            res = analyzer.estimate(item)
        except ValueError as e:
            st.error(str(e))
        else:
            m1, m2, m3, m4 = st.columns(4)
            m1.metric("Asking price", f"Rs {res['listed_price']:,.0f}")
            m2.metric("Estimated fair price", f"Rs {res['fair_price']:,.0f}")
            m3.metric("Difference", f"{res['diff_pct']:+.1f}%")
            m4.metric("Comparable listings", res["comparables"])
            verdict = res["verdict"]
            (st.error if "over" in verdict else st.success if "under" in verdict
             else st.info)(verdict)
            st.write(f"Market average: Rs {res['market_average']:,.0f} "
                     f"(std dev Rs {res['std_dev']:,.0f})")
            comp = analyzer.comparables(item)
            st.pyplot(viz.comparison_chart(comp["listed_price"], asking, res["fair_price"]))
            st.caption("Estimate uses weighted median of the most similar listings "
                       "after IQR outlier removal. Not a verified valuation.")

# ---------------------------------------------------------- Browse Listings
elif page == "Browse Listings":
    c1, c2, c3 = st.columns(3)
    text = c1.text_input("Search brand or model")
    category = c2.selectbox("Category", ["All"] + sorted(df["category"].unique()))
    lo, hi = int(df["listed_price"].min()), int(df["listed_price"].max())
    price_range = c3.slider("Price range (Rs)", lo, hi, (lo, hi))
    result = inv.search(text, None if category == "All" else category,
                        min_price=price_range[0], max_price=price_range[1])
    st.write(f"{len(result)} listings")
    st.dataframe(result)
    if len(result):
        st.json(summary_stats(result["listed_price"]))

# -------------------------------------------------------- Manage Listings
elif page == "Manage Listings":
    tab_add, tab_update, tab_delete = st.tabs(["Add", "Update", "Delete"])

    with tab_add:
        with st.container():
            a1, a2, a3 = st.columns(3)
            category = a1.selectbox("Category", ["Laptop", "Smartphone", "Tablet"], key="a_cat")
            brand = a2.text_input("Brand", key="a_brand")
            model = a3.text_input("Model", key="a_model")
            a4, a5, a6, a7 = st.columns(4)
            release_year = a4.number_input("Release year", 2000, CURRENT_YEAR, 2020, key="a_ry")
            condition = a5.selectbox("Condition", CONDITIONS, key="a_cond")
            ram = a6.number_input("RAM (GB)", 1, 128, 8, key="a_ram")
            storage = a7.number_input("Storage (GB)", 16, 4096, 256, key="a_sto")
            a8, a9, a10 = st.columns(3)
            processor = a8.text_input("Processor", "N/A", key="a_proc")
            original = a9.number_input("Original price (Rs)", 0, 1000000, 50000, key="a_op")
            listed = a10.number_input("Listed price (Rs)", 0, 1000000, 20000, key="a_lp")
            if st.button("Add listing"):
                try:
                    pid = inv.add(dict(category=category, brand=brand.strip(), model=model.strip(),
                                       release_year=release_year, condition=condition,
                                       ram_gb=ram, storage_gb=storage, processor=processor,
                                       original_price=original, listed_price=listed))
                    st.success(f"Added {pid}")
                except ValidationError as e:
                    st.error(str(e))

    with tab_update:
        pid = st.selectbox("Product ID", df["product_id"], key="u_pid")
        row = df[df["product_id"] == pid].iloc[0]
        new_price = st.number_input("New listed price (Rs)", 1, 1000000,
                                    int(row["listed_price"]), key="u_price")
        new_cond = st.selectbox("New condition", CONDITIONS,
                                index=CONDITIONS.index(row["condition"]), key="u_cond")
        if st.button("Update listing"):
            try:
                inv.update(pid, listed_price=new_price, condition=new_cond)
                st.success(f"Updated {pid}")
            except (ValidationError, KeyError) as e:
                st.error(str(e))

    with tab_delete:
        pid = st.selectbox("Product ID to delete", df["product_id"], key="d_pid")
        if st.button("Delete listing"):
            st.success(f"Deleted {pid}") if inv.delete(pid) else st.error("Not found")

# ----------------------------------------------------------- Brand Analysis
elif page == "Brand Analysis":
    category = st.selectbox("Category", ["All"] + sorted(df["category"].unique()))
    sub = df if category == "All" else df[df["category"] == category]
    st.pyplot(viz.brand_comparison(sub))
    table = (sub.groupby("brand")
                .agg(listings=("listed_price", "count"),
                     avg_price=("listed_price", "mean"),
                     median_price=("listed_price", "median"),
                     std_price=("listed_price", "std"),
                     avg_retained_pct=("retained_pct", "mean"))
                .round(1).sort_values("avg_price", ascending=False))
    st.dataframe(table)

# ------------------------------------------------------------- Depreciation
elif page == "Depreciation":
    st.pyplot(viz.depreciation_curve(df))
    c1, c2 = st.columns(2)
    c1.subheader("Retained value by age")
    c1.dataframe(depreciation_by_age(df))
    c2.subheader("Estimated yearly depreciation")
    c2.dataframe(depreciation_by_category(df))
    rate = fit_depreciation_rate(df)
    st.write(f"Overall estimated depreciation: about {rate * 100:.1f}% per year")
    st.subheader("Resale value calculator")
    o = st.number_input("Original price (Rs)", 1000, 1000000, 50000, step=1000)
    a = st.slider("Age (years)", 0, 10, 3)
    st.metric("Estimated resale value", f"Rs {predict_value(o, a, rate):,.0f}")
